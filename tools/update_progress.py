#!/usr/bin/env python3
"""Automate decompilation progress updates, reports, treemaps, and README documentation.

Performs all steps required to synchronize and verify progress across:
  1. docs/data/code_data_ownership.json (ROM ownership partition)
  2. docs/data/independent_slice.json (independent slice manifest)
  3. objdiff.json (per-function objdiff configuration)
  4. docs/data/source_quality.json (asm / partial / C classification)
  5. docs/data/report.json (objdiff v2 report; matched = decompiled C only)
  6. docs/data/report-inputs.json (CI integrity snapshot)
  7. README.md (generated progress block between progress markers)
  8. build/treemap/ (local 3D cushion treemap PNGs and interactive HTML)
  9. make ci-check (full CI gate verification)

Usage:
  python3 tools/update_progress.py [options]
  make update-progress
"""
from __future__ import annotations

import argparse
import contextlib
import io
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
README_PATH = ROOT / "README.md"
MANIFEST_PATH = ROOT / "tools/matching_slice_functions.json"
REPORT_PATH = ROOT / "docs/data/report.json"
STAMP_PATH = ROOT / "docs/data/report-inputs.json"
OWNERSHIP_PATH = ROOT / "docs/data/code_data_ownership.json"
SLICE_PATH = ROOT / "docs/data/independent_slice.json"
OBJDIFF_PATH = ROOT / "objdiff.json"
QUALITY_PATH = ROOT / "docs/data/source_quality.json"

PROGRESS_START = "<!-- progress:start (generated by tools/update_progress.py) -->"
PROGRESS_END = "<!-- progress:end -->"
QUALITY_ROWS = (
    ("c", "Plain C", "yes"),
    ("c_fakematch", "C with matching tricks (empty barriers, register pins, directives)", "yes"),
    ("partial", "C with instructions spliced in through `asm()`", "no"),
    ("asm", "Assembly in C files (naked or asm-dominated bodies)", "no"),
)


def run_cmd(cmd: list[str], cwd: Path = ROOT, check: bool = True) -> subprocess.CompletedProcess:
    """Run a subprocess command and display it clearly on failure."""
    res = subprocess.run(cmd, cwd=cwd, text=True, capture_output=True)
    if check and res.returncode != 0:
        err_msg = (res.stderr.strip() or res.stdout.strip())
        print(f"Error running {' '.join(cmd)}:\n{err_msg}", file=sys.stderr)
        res.check_returncode()
    return res


def compute_manifest_stats(manifest_file: Path = MANIFEST_PATH) -> tuple[int, int]:
    """Return (count, total_bytes) of selected C functions in the manifest."""
    manifest = json.loads(manifest_file.read_text())
    count = len(manifest)
    total_bytes = sum(int(entry["end_vma"], 16) - int(start, 16) for start, entry in manifest.items())
    return count, total_bytes


def progress_figures(report: dict, quality: dict, manifest: dict) -> dict:
    """Decompilation figures shared by the README block and the summary."""
    measures = report.get("measures", {})
    selected = {int(start, 16) for start in manifest}
    functions = [item for unit in report.get("units", []) for item in unit.get("functions", [])]
    not_in_c = [item for item in functions
                if int(item.get("metadata", {}).get("virtual_address", "0")) not in selected]
    sections = sum(int(section["size"]) for unit in report.get("units", [])
                   for section in unit.get("sections", []))
    return {
        "decompiled_bytes": int(measures.get("matched_code", 0)),
        "total_code": int(measures.get("total_code", 0)),
        "decompiled_functions": int(measures.get("matched_functions", 0)),
        "total_functions": int(measures.get("total_functions", 0)),
        "totals": quality["totals"],
        "not_in_c_functions": len(not_in_c),
        "not_in_c_bytes": sum(int(item["size"]) for item in not_in_c),
        "non_function_bytes": sections,
    }


def progress_block(fig: dict) -> str:
    """Markdown for the README progress block; deterministic for --check."""
    def pct(part: int, whole: int) -> str:
        return f"{100 * part / whole:.2f}%" if whole else "0.00%"

    rows = [
        f"**Decompiled to C: {fig['decompiled_bytes']:,} / {fig['total_code']:,} executable bytes "
        f"({pct(fig['decompiled_bytes'], fig['total_code'])}), "
        f"{fig['decompiled_functions']:,} / {fig['total_functions']:,} functions "
        f"({pct(fig['decompiled_functions'], fig['total_functions'])}).**",
        "",
        "| Source form | Functions | Bytes | Share of code | Counts as decompiled |",
        "| --- | ---: | ---: | ---: | :---: |",
    ]
    for cls, label, counted in QUALITY_ROWS:
        t = fig["totals"][cls]
        rows.append(f"| {label} | {t['functions']:,} | {t['bytes']:,} | "
                    f"{pct(t['bytes'], fig['total_code'])} | {counted} |")
    rows.append(f"| Identified function not yet selected for C | {fig['not_in_c_functions']:,} | "
                f"{fig['not_in_c_bytes']:,} | {pct(fig['not_in_c_bytes'], fig['total_code'])} | no |")
    rows.append(f"| Non-function bytes (header, startup, pools) | - | {fig['non_function_bytes']:,} | "
                f"{pct(fig['non_function_bytes'], fig['total_code'])} | no |")
    return "\n".join(rows)


def format_readme(content: str, block: str) -> tuple[str, bool]:
    """Replace the text between the progress markers with `block`."""
    start = content.find(PROGRESS_START)
    end = content.find(PROGRESS_END)
    if start < 0 or end < start:
        raise ValueError("README.md is missing the progress markers")
    updated = (content[:start + len(PROGRESS_START)] + "\n" + block + "\n"
               + content[end:])
    return updated, updated != content


def readme_block(root: Path = ROOT) -> str:
    report = json.loads((root / REPORT_PATH).read_text())
    quality = json.loads((root / QUALITY_PATH).read_text())
    manifest = json.loads((root / MANIFEST_PATH).read_text())
    return progress_block(progress_figures(report, quality, manifest))


def update_ownership_and_slice(root: Path = ROOT, verbose: bool = True) -> None:
    """Regenerate ownership map and independent slice inventory."""
    if verbose:
        print("[1/6] Refreshing ROM code/data ownership and slice manifests...")
    run_cmd([sys.executable, "tools/ownership_map.py", "--write"], cwd=root)
    run_cmd([sys.executable, "tools/independent_slice.py", "--write"], cwd=root)


def update_objdiff_config(root: Path = ROOT, verbose: bool = True) -> None:
    """Regenerate objdiff.json configuration."""
    if verbose:
        print("[2/6] Refreshing objdiff configuration...")
    run_cmd([sys.executable, "tools/objdiff_build.py", "--configure"], cwd=root)


def refresh_decomp_report(root: Path = ROOT, verbose: bool = True) -> None:
    """Classify source forms, run full verification, and refresh the report."""
    if verbose:
        print("[3/6] Classifying source forms, running verification gate & refreshing report...")
    run_cmd([sys.executable, "tools/source_quality.py", "--write"], cwd=root)
    run_cmd([sys.executable, "tools/decomp_report.py", "--refresh"], cwd=root)


def update_readme_file(root: Path = ROOT, verbose: bool = True) -> bool:
    """Regenerate the README progress block from the report and classification."""
    if verbose:
        print("[4/6] Updating README.md progress block...")
    readme_file = root / "README.md"
    updated, changed = format_readme(readme_file.read_text(), readme_block(root))
    if changed:
        readme_file.write_text(updated)
    if verbose:
        print("      README.md updated" if changed else "      README.md is already up to date")
    return changed


def generate_treemaps(root: Path = ROOT, verbose: bool = True) -> bool:
    """Generate local 3D cushion treemap PNG images and interactive HTML viewers."""
    if verbose:
        print("[5/6] Generating local treemap visualizations...")
    try:
        import numpy  # noqa: F401
        from PIL import Image  # noqa: F401
    except ImportError:
        if verbose:
            print("      Pillow/numpy not available in Python environment; skipping local PNG treemap.")
        return False

    out_dir = root / "build/treemap"
    out_dir.mkdir(parents=True, exist_ok=True)
    run_cmd([
        sys.executable, "tools/treemap.py",
        "--mode", "independent",
        "--out", "build/treemap/treemap_independent.png",
        "--html", "build/treemap/independent.html",
    ], cwd=root)
    run_cmd([
        sys.executable, "tools/treemap.py",
        "--mode", "subsystem",
        "--out", "build/treemap/treemap_subsystem.png",
        "--html", "build/treemap/subsystem.html",
    ], cwd=root)
    if verbose:
        print("      Treemaps generated at build/treemap/treemap_independent.png and subsystem.png")
    return True


def run_ci_verification(root: Path = ROOT, verbose: bool = True) -> None:
    """Verify that ROM-free CI checks and snapshot fingerprints pass."""
    if verbose:
        print("[6/6] Verifying CI checks (make ci-check)...")
    run_cmd(["make", "ci-check"], cwd=root)
    if verbose:
        print("      make ci-check PASS -- all integrity gates and self-tests passed.")


def print_summary(root: Path = ROOT) -> None:
    """Display matching, linkage, data, and outstanding gates separately."""
    report_file = root / REPORT_PATH
    if not report_file.exists():
        print("Summary unavailable: report.json does not exist.")
        return

    report = json.loads(report_file.read_text())
    measures = report.get("measures", {})

    linked_code = int(measures.get("complete_code", 0))
    linked_code_pct = float(measures.get("complete_code_percent", 0.0))
    total_code = int(measures.get("total_code", 0))
    quality_file = root / QUALITY_PATH
    fig = None
    if quality_file.is_file():
        fig = progress_figures(report, json.loads(quality_file.read_text()),
                               json.loads((root / MANIFEST_PATH).read_text()))
    matched_data = int(measures.get("matched_data", 0))
    total_data = int(measures.get("total_data", 0))
    matched_data_pct = float(measures.get("matched_data_percent", 0.0))
    linked_data = int(measures.get("complete_data", 0))
    linked_data_pct = float(measures.get("complete_data_percent", 0.0))

    verification = {}
    stamp_file = root / STAMP_PATH
    if stamp_file.is_file():
        try:
            verification = json.loads(stamp_file.read_text()).get("verification", {})
        except (OSError, ValueError, TypeError):
            pass
    ownership_file = root / OWNERSHIP_PATH
    padding_bytes = 0
    if ownership_file.is_file():
        try:
            ownership = json.loads(ownership_file.read_text())
            padding_bytes = sum(
                int(row["size"]) for row in ownership.get("segments", [])
                if row.get("classification") == "padding")
        except (OSError, ValueError, TypeError, KeyError):
            pass

    print("\n" + "=" * 65)
    print("       GT ADVANCE 3 MATCHING AND LINK STATUS")
    print("=" * 65)
    print("  Decompilation (bytes the compiler produces from C):")
    if fig is None:
        print("    Unavailable: docs/data/source_quality.json does not exist.")
    else:
        total = fig["total_code"]
        print(f"    Decompiled code bytes:  {fig['decompiled_bytes']:,} / {total:,} "
              f"({100 * fig['decompiled_bytes'] / total if total else 0:.2f}%)")
        print(f"    Decompiled functions:   {fig['decompiled_functions']:,} / {fig['total_functions']:,}")
        for cls, label, counted in QUALITY_ROWS:
            t = fig["totals"][cls]
            print(f"      {cls:12s} {t['functions']:5,d} fns {t['bytes']:7,d} B  "
                  f"({'counted' if counted == 'yes' else 'not counted'})")
    print("  Link/build evidence:")
    print(f"    C/ASM code slice linked: {linked_code:,} / {total_code:,} ({linked_code_pct:.2f}%)")
    reference_status = verification.get("reference_rom", "not_verified")
    print(f"    Reference ROM build:    {reference_status.upper().replace('_', ' ')}")
    rom_link_status = verification.get("full_hybrid_rom_link", "not_verified")
    print(f"    Full C/ASM + data link:  {rom_link_status.upper().replace('_', ' ')}")
    census_status = verification.get("function_entry_census", "not_verified")
    print(f"    Function-entry census:  {census_status.upper().replace('_', ' ')}")
    print("    Runtime equivalence:    NOT RUN (separate from byte identity)")
    print("  Data byte reconstruction (non-padding):")
    print(f"    Reproduced data bytes:  {matched_data:,} / {total_data:,} ({matched_data_pct:.2f}%)")
    print(f"    Data linked to build:  {linked_data:,} / {total_data:,} ({linked_data_pct:.2f}%)")
    print(f"    ROM padding excluded:  {padding_bytes:,} bytes")
    print("    Semantic asset decoding is not measured by this byte-progress report.")
    if census_status == "pass":
        print(f"  Census evidence: {int(measures.get('total_functions', 0)):,} entries; 0 unresolved.")
    print("-" * 65)
    print("  Artifacts ready for commit:")
    print("    • docs/data/code_data_ownership.json")
    print("    • docs/data/independent_slice.json")
    print("    • docs/data/source_quality.json  (asm / partial / C classification)")
    print("    • docs/data/report.json          (objdiff v2 report)")
    print("    • docs/data/report-inputs.json   (CI integrity fingerprint)")
    print("    • objdiff.json")
    print("    • README.md")
    print("-" * 65)
    print("  Recommended commit command:")
    print("    git add docs/data/report.json docs/data/report-inputs.json docs/data/source_quality.json \\")
    print("            docs/data/code_data_ownership.json docs/data/independent_slice.json \\")
    print("            objdiff.json README.md")
    if fig is not None:
        print(f'    git commit -m "Progress: {fig["decompiled_functions"]:,}/{fig["total_functions"]:,} '
              f'functions decompiled to C"')
    print("=" * 65 + "\n")


class SelfTests(unittest.TestCase):
    def test_readme_block_replaced_between_markers(self):
        sample = f"# Header\n{PROGRESS_START}\nold text\n{PROGRESS_END}\nTail.\n"
        updated, changed = format_readme(sample, "new block")
        self.assertTrue(changed)
        self.assertEqual(updated, f"# Header\n{PROGRESS_START}\nnew block\n{PROGRESS_END}\nTail.\n")
        self.assertEqual(format_readme(updated, "new block"), (updated, False))
        with self.assertRaisesRegex(ValueError, "markers"):
            format_readme("# no markers\n", "x")

    def test_manifest_stats(self):
        count, total = compute_manifest_stats(ROOT / "tools/matching_slice_functions.json")
        self.assertGreater(count, 1000)
        self.assertGreater(total, 50000)

    def test_summary_reports_decompiled_c_separately_from_link(self):
        with tempfile.TemporaryDirectory() as temp_dir, patch.multiple(
                __name__,
                MANIFEST_PATH=Path("tools/matching_slice_functions.json"),
                REPORT_PATH=Path("docs/data/report.json"),
                STAMP_PATH=Path("docs/data/report-inputs.json"),
                OWNERSHIP_PATH=Path("docs/data/code_data_ownership.json"),
                QUALITY_PATH=Path("docs/data/source_quality.json")):
            root = Path(temp_dir)
            (root / "tools").mkdir()
            (root / "docs/data").mkdir(parents=True)
            (root / MANIFEST_PATH).write_text(json.dumps({
                "0x08000000": {"end_vma": "0x08000010", "c_name": "candidate"},
                "0x08000010": {"end_vma": "0x08000030", "c_name": "naked"},
            }))
            (root / REPORT_PATH).write_text(json.dumps({"measures": {
                "matched_code": "16", "total_code": "100", "matched_code_percent": 16.0,
                "complete_code": "100", "complete_code_percent": 100.0,
                "matched_functions": 1, "total_functions": 3,
                "matched_functions_percent": 100 / 3,
                "matched_data": "20", "total_data": "20", "matched_data_percent": 100.0,
                "complete_data": "20", "complete_data_percent": 100.0,
            }, "units": [{"functions": [
                {"name": "candidate", "size": "16", "fuzzy_match_percent": 100.0,
                 "metadata": {"virtual_address": "134217728"}},
                {"name": "naked", "size": "32", "fuzzy_match_percent": 0.0,
                 "metadata": {"virtual_address": "134217744"}},
                {"name": "_08000030", "size": "40", "fuzzy_match_percent": 0.0,
                 "metadata": {"virtual_address": "134217776"}},
            ], "sections": [{"size": "12"}]}]}))
            (root / QUALITY_PATH).write_text(json.dumps({"totals": {
                "c": {"functions": 1, "bytes": 16},
                "c_fakematch": {"functions": 0, "bytes": 0},
                "partial": {"functions": 0, "bytes": 0},
                "asm": {"functions": 1, "bytes": 32},
            }}))
            (root / STAMP_PATH).write_text(json.dumps({
                "verification": {"reference_rom": "pass", "full_hybrid_rom_link": "pass"}
            }))
            (root / OWNERSHIP_PATH).write_text(json.dumps({"segments": [
                {"size": 5, "classification": "padding"}
            ]}))

            output = io.StringIO()
            with contextlib.redirect_stdout(output):
                print_summary(root)
            summary = output.getvalue()
            self.assertIn("Decompiled code bytes:  16 / 100 (16.00%)", summary)
            self.assertIn("Decompiled functions:   1 / 3", summary)
            self.assertIn("C/ASM code slice linked: 100 / 100 (100.00%)", summary)
            self.assertIn("Full C/ASM + data link:  PASS", summary)

            block = readme_block(root)
            self.assertIn("**Decompiled to C: 16 / 100 executable bytes (16.00%), "
                          "1 / 3 functions (33.33%).**", block)
            self.assertIn("| Assembly in C files (naked or asm-dominated bodies) | 1 | 32 | 32.00% | no |", block)
            self.assertIn("| Identified function not yet selected for C | 1 | 40 | 40.00% | no |", block)
            self.assertIn("| Non-function bytes (header, startup, pools) | - | 12 | 12.00% | no |", block)

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--self-test", action="store_true", help="Run internal unit tests and exit.")
    parser.add_argument("--check", action="store_true", help="Check whether README and reports are up to date.")
    parser.add_argument("--skip-build", "--fast", action="store_true", help="Skip matching build gate; update files only.")
    parser.add_argument("--no-treemap", action="store_true", help="Skip local cushion treemap rendering.")
    parser.add_argument("--no-ci-check", action="store_true", help="Skip running make ci-check.")
    args = parser.parse_args()

    if args.self_test:
        suite = unittest.TestLoader().loadTestsFromTestCase(SelfTests)
        result = unittest.TextTestRunner(verbosity=2).run(suite)
        sys.exit(0 if result.wasSuccessful() else 1)

    if args.check:
        _, changed = format_readme(README_PATH.read_text(), readme_block(ROOT))
        if changed:
            print("README.md progress block is stale; run python3 tools/update_progress.py", file=sys.stderr)
            sys.exit(1)
        res = subprocess.run([sys.executable, "tools/decomp_report.py"], cwd=ROOT)
        sys.exit(res.returncode)

    print("=== Updating GT Advance 3 Decompilation Progress ===")
    t0 = time.time()

    # Step 1: Update code/data ownership & independent slice manifests
    update_ownership_and_slice(ROOT)

    # Step 2: Refresh objdiff configuration
    update_objdiff_config(ROOT)

    # Step 3: Classify sources, verify build and refresh the report (unless --skip-build)
    if not args.skip_build:
        refresh_decomp_report(ROOT)
    else:
        print("[3/6] Skipping full build gate (--skip-build requested).")

    # Step 4: Regenerate the README progress block
    update_readme_file(ROOT)

    # Step 5: Render local treemaps
    if not args.no_treemap:
        generate_treemaps(ROOT)
    else:
        print("[5/6] Skipping local treemap rendering (--no-treemap requested).")

    # Step 6: Verify CI checks
    if not args.no_ci_check:
        run_ci_verification(ROOT)
    else:
        print("[6/6] Skipping CI verification (--no-ci-check requested).")

    # Print summary
    print_summary(ROOT)
    elapsed = time.time() - t0
    print(f"Progress update complete in {elapsed:.1f}s.")


if __name__ == "__main__":
    main()
