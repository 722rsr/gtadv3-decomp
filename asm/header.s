@ This file replaces the former `.incbin "baserom.gba", 0x000000, 0x0000C0`.
@ Every field is named rather than copied, and the two integrity bytes are
@ documented and re-verified by tools/independent_slice.py:
@
@   * 0x000B D header complement checksum — -(sum of the bytes 0x0A0..0x0BC)
@     - 0x19, i.e. 0xE3 for these fields.  The checker recomputes it from the
@     emitted image, so changing the title, code, maker, fixed byte or
@     version without updating it fails.
@   * 0x000BE global checksum — the retail image stores 0x0000 here instead of
@     the computed halfword sum, so the reconstructed source must emit the
@     same literal to stay byte-identical.  This is a known quirk of several
@     GBA titles and is recorded here rather than silently "fixed".
@
@ Field map (GBATEK "GBA Cartridge Header"):
@   0x000  ARM branch to crt0 (0x080000C0, asm/boot.s)
@   0x004  Nintendo boot logo — 156-byte fixed constant, identical in every
@          licensed GBA cartridge; the BIOS compares it before booting
@   0x0A0  game title, 12 ASCII bytes
@   0x0AC  game code, 4 ASCII bytes        ("A2GE")
@   0x0B0  maker code, 2 ASCII bytes       ("78" = MTO)
@   0x0B2  fixed value 0x96
@   0x0B3  main unit code / device type / reserved — all zero on this cart
@   0x0BC  software version (0)
@   0x0BD  header complement checksum (0xE3)
@   0x0BE  global checksum (not written by the toolchain; zero)

